    """Generates the full dummy catalog, marking every product as is_dummy=True."""
    catalog = []
    for item in RAW_CATALOG:
        doc = {
            **item,
            "is_dummy": True,
            "active": True,
            "metadata": {
                "dataset": "development_dummy",
                "stress_test": True,
                "verified_family_rate": False,
            },
        }
        catalog.append(doc)

    with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
        json.dump(catalog, f, indent=2, ensure_ascii=False)

    print(f"Generated {len(catalog)} realistic dummy products into {OUTPUT_FILE}")
    return len(catalog)


